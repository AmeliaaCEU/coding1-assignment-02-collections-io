drink = "tea" #defines the variable drink as "tea"
sales = {"tea": 3, "coffee": 5} #defines a dictionary called sales with keys "tea" and "coffee" values for each
sold = sales[drink] #uses sales dictionary to find the value of the key "tea" and assigns it to the variable sold
sold = sold + 1 #adds 1 to the value of sold
print(drink) #prints the value of the variable drink
print(sold) #prints the number of drinks sold after adding above.
